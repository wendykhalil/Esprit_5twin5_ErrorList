<?php

namespace App\Http\Controllers\Admin;

use App\Http\Controllers\Controller;
use App\Services\SolarShareAIService;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Validator;
use RuntimeException;
use Throwable;

class EquipmentDescriptionAIController extends Controller
{
    public function generate(
        Request $request,
        SolarShareAIService $ai
    ): JsonResponse {
        $validated = $request->validate([
            'name' => 'required|string|min:3|max:255',
            'category' => 'nullable|string|max:255',
            'brand' => 'nullable|string|max:255',
            'power' => 'nullable|numeric|min:0|max:999999',
            'capacity' => 'nullable|numeric|min:0|max:999999',
            'condition' => 'nullable|in:excellent,good,used',
        ]);

        try {
            $raw = $ai->generateEquipmentDescription(
                $validated
            );

            $result = $this->decodeAIJson($raw);

            /*
             * Only validate the description generated by AI.
             * Technical values are verified independently
             * against submitted equipment information.
             */
            $validator = Validator::make($result, [
                'description' => [
                    'required',
                    'string',
                    'min:10',
                    'max:1000',
                ],
            ]);

            if ($validator->fails()) {
                throw new RuntimeException(
                    'AI response validation failed: ' .
                    $validator->errors()->first()
                );
            }

            $power = $this->verifiedValue(
                $validated,
                'power',
                'W',
                'kW'
            );

            $capacity = $this->verifiedValue(
                $validated,
                'capacity',
                'Wh',
                'kWh'
            );

            return response()->json([
                'success' => true,
                'description' => trim(
                    $result['description']
                ),
                'power' => $power,
                'capacity' => $capacity,
            ]);

        } catch (Throwable $e) {
            report($e);

            return response()->json([
                'success' => false,
                'message' =>
                    'Impossible de générer les informations. Vérifiez Ollama et réessayez.',
            ], 503);
        }
    }

    private function decodeAIJson(string $raw): array
    {
        $raw = trim($raw);

        $raw = preg_replace(
            '/^```(?:json)?\s*|\s*```$/i',
            '',
            $raw
        );

        $raw = trim($raw);

        $decoded = json_decode($raw, true);

        if (is_array($decoded)) {
            return $decoded;
        }

        $fixed = $this->escapeJsonControlCharacters($raw);
        $decoded = json_decode($fixed, true);

        if (!is_array($decoded)) {
            throw new RuntimeException(
                'AI returned invalid JSON: ' .
                json_last_error_msg()
            );
        }

        return $decoded;
    }

    private function verifiedValue(
        array $equipment,
        string $field,
        string $unit,
        string $largerUnit
    ): ?float {
        /*
         * Values already entered by the admin
         * take priority over extracted values.
         */
        if (
            isset($equipment[$field]) &&
            is_numeric($equipment[$field])
        ) {
            return (float) $equipment[$field];
        }

        $name = (string) ($equipment['name'] ?? '');

        /*
         * Match larger units first:
         * kW before W, kWh before Wh.
         */
        $pattern = '/(?<![\d\w])(\d+(?:[.,]\d+)?)\s*(' .
            preg_quote($largerUnit, '/') . '|' .
            preg_quote($unit, '/') .
            ')(?![a-zA-Z])/i';

        if (!preg_match($pattern, $name, $matches)) {
            return null;
        }

        $value = (float) str_replace(
            ',',
            '.',
            $matches[1]
        );

        $matchedUnit = strtolower($matches[2]);

        if ($matchedUnit === strtolower($largerUnit)) {
            $value *= 1000;
        }

        if ($value < 0 || $value > 999999) {
            return null;
        }

        return $value;
    }

    private function escapeJsonControlCharacters(
        string $json
    ): string {
        $result = '';
        $insideString = false;
        $escaped = false;

        $length = strlen($json);

        for ($i = 0; $i < $length; $i++) {
            $char = $json[$i];

            if ($escaped) {
                $result .= $char;
                $escaped = false;
                continue;
            }

            if ($insideString && $char === '\\') {
                $result .= $char;
                $escaped = true;
                continue;
            }

            if ($char === '"') {
                $insideString = !$insideString;
                $result .= $char;
                continue;
            }

            if ($insideString) {
                switch ($char) {
                    case "\n":
                        $result .= '\\n';
                        continue 2;

                    case "\r":
                        $result .= '\\r';
                        continue 2;

                    case "\t":
                        $result .= '\\t';
                        continue 2;
                }

                if (ord($char) < 32) {
                    $result .= sprintf(
                        '\\u%04x',
                        ord($char)
                    );
                    continue;
                }
            }

            $result .= $char;
        }

        return $result;
    }
}
